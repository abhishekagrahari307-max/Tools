// Structural checks for the Studio Hub pages — no browser required.
//   node --test tests/
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync, statSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const PAGES = ['index.html', 'audio-video/index.html', 'pixora/index.html'];

test('every page exists and is not empty', () => {
  for (const page of PAGES) {
    assert.ok(existsSync(join(root, page)), `${page} is missing`);
    assert.ok(statSync(join(root, page)).size > 1000, `${page} looks empty`);
  }
});

test('landing page links to both studios', () => {
  const html = read('index.html');
  for (const href of ['audio-video/', 'pixora/', 'assets/hub.css', 'manifest.webmanifest']) {
    assert.ok(html.includes(`href="${href}"`), `landing page does not link ${href}`);
  }
  assert.match(html, /Audio &amp; Video Editor/);
  assert.match(html, /Image &amp; PDF Studio/);
});

test('every local href/src on every page resolves', () => {
  for (const page of PAGES) {
    const html = read(page);
    const refs = [...html.matchAll(/(?:href|src)="([^"]+)"/g)].map((m) => m[1]);
    for (const ref of refs) {
      if (/^(?:[a-z]+:|\/\/|#|data:)/i.test(ref)) continue;
      // Inside the studios, markup is generated by JS template strings, so only
      // treat a reference as a real asset when it resolves to a path on disk.
      if (!existsSync(resolve(dirname(join(root, page)), ref.split('#')[0].split('?')[0]))) {
        if (/[\s${}'"`+()]/.test(ref)) continue; // runtime-built value, not a literal path
      }
      const clean = ref.split('#')[0].split('?')[0];
      if (!clean) continue;
      const target = resolve(dirname(join(root, page)), clean);
      assert.ok(existsSync(target), `${page} → ${ref} does not exist`);
    }
  }
});

test('no page loads a script or stylesheet from a remote host', () => {
  for (const page of PAGES) {
    const html = read(page);
    const remote = [...html.matchAll(/<(?:script|link)\b[^>]*(?:src|href)="(https?:\/\/[^"]+)"/gi)];
    assert.equal(remote.length, 0,
      `${page} loads ${remote.map((m) => m[1]).join(', ')} — everything must be served locally`);
  }
});

test('audio & video studio stays a single dependency-free file', () => {
  const html = read('audio-video/index.html');
  assert.ok(!/from '\.\/js\//.test(html), 'reference to a pipeline module that is not shipped');
  const title = (html.match(/<title>([^<]*)<\/title>/) || [])[1] || '';
  assert.match(title, /59 Tools/, 'the page title should state the current tool count');
  assert.ok(!/images\.unsplash\.com|picsum\.photos/.test(html), 'demo artwork must be self-contained');
  assert.ok(statSync(join(root, 'audio-video/index.html')).size < 1_500_000, 'page grew unexpectedly');
});

test('pixora keeps its engines out of the HTML and on disk', () => {
  const html = read('pixora/index.html');
  assert.ok(html.length < 400_000, 'pixora/index.html must stay a thin shell');
  assert.ok(html.includes("vendor/boot.js"), 'the boot loader is missing');
  for (const lib of ['fabric', 'pdf-lib', 'pdfjs', 'jszip', 'fontkit', 'tesseract', 'local-engines', 'app', 'boot']) {
    assert.ok(existsSync(join(root, `pixora/vendor/${lib}.js`)), `pixora/vendor/${lib}.js is missing`);
  }
  const app = read('pixora/vendor/app.js');
  assert.ok(app.includes('renderCards()'), 'vendor/app.js does not look like the studio bundle');
  assert.ok(!/id="(?:qpdfWasm|tessCoreCode|pdfWorkerCode|bundledHindiFont)"/.test(html),
    'a heavy engine is still inlined');
  assert.ok(html.includes('EngineStore'), 'EngineStore loader is missing');
  for (const id of ['qpdfWasm', 'tessCoreCode', 'tessWorkerCode', 'pdfWorkerCode', 'bundledHindiFont']) {
    assert.ok(html.includes(id), `EngineStore no longer maps ${id}`);
  }
  const engines = readdirSync(join(root, 'pixora/engines'));
  for (const file of ['qpdf.wasm.b64', 'qpdf-worker.js', 'pdfjs-worker.js', 'tesseract-core.js',
    'tesseract-worker.js', 'tesseract-eng.traineddata.gz.b64', 'tesseract-hin.traineddata.gz.b64',
    'hindi-font.ttf.b64']) {
    assert.ok(engines.includes(file), `pixora/engines/${file} is missing`);
  }
});

test('external affiliate library is gone', () => {
  const html = read('pixora/index.html');
  assert.ok(!/EXTERNAL_TOOLS/.test(html));
  assert.ok(!/pi7\.org|pixellab\.studio/.test(html), 'affiliate links should not ship');
  assert.ok(existsSync(join(root, 'pixora/THIRD-PARTY-LICENSES.txt')), 'licence text must be kept');
});

test('the three converter/resizer tools are wired into the audio & video studio', () => {
  const html = read('audio-video/index.html');
  for (const id of ['aconv', 'vconv', 'vresize']) {
    assert.ok(html.includes(`id:'${id}'`) || html.includes(`id: '${id}'`), `${id} is missing from the tool catalogue`);
    assert.ok(new RegExp(`${id}\\s*:\\s*render`).test(html), `${id} has no route`);
  }
  for (const fn of ['encodeAudio', 'recordVideoAdvanced', 'pickVideoMime']) {
    assert.ok(html.includes(`function ${fn}`), `${fn} helper is missing`);
  }
});

test('inline scripts on every page parse as JavaScript', () => {
  // A cheap structural check: balanced braces/parens outside of strings is overkill here,
  // so instead assert that no page has an unclosed <script> tag.
  for (const page of PAGES) {
    const html = read(page);
    const open = (html.match(/<script\b/gi) || []).length;
    const close = (html.match(/<\/script>/gi) || []).length;
    assert.equal(open, close, `${page} has unbalanced <script> tags`);
  }
});
